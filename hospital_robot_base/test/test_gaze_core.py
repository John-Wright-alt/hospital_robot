"""Unit tests for gaze_core.py.

ALL scans in this file are SYNTHETIC (generated by fake_scan below): a
rectangular room plus round objects, with LD06-like beam spacing and noise.
They test the logic only. They are not real sensor observations.

    python3 -m pytest test/test_gaze_core.py -v      (from inside the package folder)
"""

import math

import numpy as np
import pytest

from hospital_robot_base.gaze_core import (
    GazeEngine, GazeParams, bin_scan)

RNG = np.random.default_rng(1)
N_BEAMS = 450                                 # ~ LD06 at 10 Hz
INC = 2 * math.pi / N_BEAMS
ROOM = (-1.2, 2.0, -1.5, 1.5)                 # x_min, x_max, y_min, y_max (m)


def fake_scan(objects=(), noise=0.01, n=N_BEAMS, dropout=0.0):
    """SYNTHETIC scan. objects = [(x, y, radius), ...] in the scan frame."""
    out = np.empty(n)
    for i in range(n):
        a = i * 2 * math.pi / n
        dx, dy = math.cos(a), math.sin(a)
        best = math.inf
        x0, x1, y0, y1 = ROOM
        for d, lo, hi in ((dx, x0, x1), (dy, y0, y1)):
            if d > 1e-9:
                best = min(best, hi / d)
            elif d < -1e-9:
                best = min(best, lo / d)
        for ox, oy, rad in objects:               # ray-circle intersection
            b = dx * ox + dy * oy
            c = ox * ox + oy * oy - rad * rad
            disc = b * b - c
            if disc >= 0 and b - math.sqrt(disc) > 0:
                best = min(best, b - math.sqrt(disc))
        out[i] = best + RNG.normal(0, noise)
        if dropout and RNG.random() < dropout:
            out[i] = 0.0                          # LD06 reports 0 for "no return"
    return out


def run(engine, t0, seconds, objects_fn, hz=10.0):
    """Feed scans for `seconds`; objects_fn(t) gives the objects at time t."""
    results = []
    t = t0
    while t < t0 + seconds - 1e-9:
        r = fake_scan(objects_fn(t))
        results.append(engine.process(r, 0.0, INC, 0.02, 12.0, t))
        t += 1.0 / hz
    return results, t


def learned_engine(params=None):
    eng = GazeEngine(params or GazeParams())
    res, t = run(eng, 0.0, 2.5, lambda t: [])
    assert res[0].state == 'learning'
    return eng, t


# ------------------------------------------------------------------ binning
def test_bin_scan_keeps_closest_and_drops_invalid():
    r = [1.0, 0.0, float('inf'), float('nan'), 0.5, 0.05]
    out = bin_scan(r, 0.0, math.radians(0.1), 0.02, 12.0, 360, 0.15, 2.5)
    assert out[0] == pytest.approx(0.5)            # all six beams fall in sector 0
    assert np.isinf(out[1:]).all()


def test_variable_beam_count_still_works():
    eng, t = learned_engine()
    # the LD06 driver does not always send the same number of points
    for n in (440, 455, 448):
        res = eng.process(fake_scan(n=n), 0.0, 2 * math.pi / n, 0.02, 12.0, t)
        t += 0.1
        assert res.state == 'none'


# ----------------------------------------------------------------- behaviour
def test_empty_room_gives_no_target_even_with_dropouts():
    eng, t = learned_engine()
    for _ in range(50):
        r = fake_scan(dropout=0.05)
        res = eng.process(r, 0.0, INC, 0.02, 12.0, t)
        t += 0.1
        assert res.state == 'none', 'static room must never attract the eyes'


def test_object_on_the_left_is_found_after_confirmation():
    eng, t = learned_engine()
    obj = (0.0, 1.0, 0.12)                          # 1 m to the robot's LEFT
    res, _ = run(eng, t, 1.0, lambda _: [obj])
    assert res[0].state == 'none'                   # one scan is not enough
    assert res[-1].state == 'tracking'
    assert math.degrees(res[-1].bearing_rad) == pytest.approx(90.0, abs=4.0)
    assert res[-1].range_m == pytest.approx(0.95, abs=0.08)


def test_object_crossing_right_to_left_is_followed():
    eng, t0 = learned_engine()
    # walks from (1.0, -1.0) to (1.0, +1.0) at 0.5 m/s, 1 m in front
    path = lambda t: [(1.0, -1.0 + 0.5 * (t - t0), 0.12)]
    res, _ = run(eng, t0, 4.0, path)
    tracking = [r for r in res if r.state == 'tracking']
    bearings = [math.degrees(r.bearing_rad) for r in tracking]
    assert len(tracking) > 30
    assert bearings[0] < -30 and bearings[-1] > 30          # right -> left
    assert all(b2 > b1 - 3 for b1, b2 in zip(bearings, bearings[1:]))  # no jumping back
    assert len({r.track_id for r in tracking}) == 1          # one ID the whole way
    assert tracking[-1].speed_mps == pytest.approx(0.5, abs=0.15)


def test_object_leaving_gives_lost_then_none():
    eng, t = learned_engine()
    _, t = run(eng, t, 1.0, lambda _: [(1.0, 0.3, 0.12)])
    res, _ = run(eng, t, 1.5, lambda _: [])
    states = [r.state for r in res]
    assert states[0] == 'lost'                      # coasting, not instantly gone
    assert states[-1] == 'none'


def test_object_that_stays_still_becomes_boring():
    p = GazeParams(absorb_s=3.0)
    eng, t = learned_engine(p)
    res, _ = run(eng, t, 6.0, lambda _: [(1.0, -0.5, 0.15)])
    assert res[5].state == 'tracking'
    assert res[-1].state == 'none'                  # absorbed into the background


def test_two_legs_are_one_object():
    eng, t = learned_engine()
    legs = [(1.0, 0.10, 0.05), (1.0, -0.10, 0.05)]   # 20 cm apart
    res, _ = run(eng, t, 1.0, lambda _: legs)
    assert res[-1].state == 'tracking'
    assert res[-1].n_objects == 1
    assert math.degrees(res[-1].bearing_rad) == pytest.approx(0.0, abs=4.0)


def test_focus_does_not_flip_between_two_similar_objects():
    eng, t = learned_engine()
    objs = [(1.0, 0.8, 0.12), (1.0, -0.8, 0.12)]
    res, _ = run(eng, t, 5.0, lambda _: objs)
    ids = [r.track_id for r in res if r.state == 'tracking']
    assert len(set(ids)) == 1


def test_frame_transform_rotates_bearing():
    # LiDAR mounted turned -90 deg (its x axis points to the robot's right),
    # like your URDF's lidar_yaw = -1.5708.
    p = GazeParams(frame_yaw=-math.pi / 2)
    eng, t = learned_engine(p)
    # In the LiDAR's own frame the object is straight ahead (+x of the LiDAR)...
    res, _ = run(eng, t, 1.0, lambda _: [(1.0, 0.0, 0.12)])
    # ...which is the ROBOT's right: bearing -90 deg
    assert math.degrees(res[-1].bearing_rad) == pytest.approx(-90.0, abs=4.0)


def test_object_across_the_zero_degree_seam_is_one_object():
    eng, t = learned_engine()
    res, _ = run(eng, t, 1.0, lambda _: [(1.0, 0.0, 0.2)])   # spans 359..1 deg
    assert res[-1].state == 'tracking' and res[-1].n_objects == 1


def test_single_sector_spike_is_ignored():
    eng, t = learned_engine()
    for _ in range(20):
        r = fake_scan()
        r[100] = 0.5                                 # one bad beam, every scan
        res = eng.process(r, 0.0, INC, 0.02, 12.0, t)
        t += 0.1
        assert res.state == 'none'


def test_reset_relearns():
    eng, t = learned_engine()
    eng.reset()
    assert eng.process(fake_scan(), 0.0, INC, 0.02, 12.0, t).state == 'learning'
